tupla1 = (17,18,19,19,18,19) # tupla
print(tupla1[4])

lista1 = [17,18,19,19,18,19] # Lista

lista1[4] = 17

print(lista1)    
print(len(lista1))

# Lista y tupla son estructuras parecidas, pero la tupla es inmutable (no se puede cambiar sus elementos)
# La lista es mutable (se pueden cambiar sus elementos)
